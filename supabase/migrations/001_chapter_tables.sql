-- ChapterHub chapter catalog schema
-- Run this in the Supabase SQL Editor for the zrrzshymjvwzxbabtkrw project.
-- Keep chapter image URLs as source URLs unless you have explicit redistribution/storage rights.

create table if not exists public.chapters (
  chapter_id text primary key,
  manga_id text not null,
  chapter_number numeric,
  title text,
  source_url text,
  published_at timestamptz,
  sort_order numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists chapters_manga_sort_idx
  on public.chapters (manga_id, sort_order desc nulls last);

create table if not exists public.chapter_pages (
  id bigint generated by default as identity primary key,
  chapter_id text not null references public.chapters(chapter_id) on delete cascade,
  page_number integer not null check (page_number > 0),
  image_url text not null,
  width integer,
  height integer,
  created_at timestamptz not null default now(),
  unique (chapter_id, page_number)
);

create index if not exists chapter_pages_chapter_page_idx
  on public.chapter_pages (chapter_id, page_number);

alter table public.chapters enable row level security;
alter table public.chapter_pages enable row level security;

drop policy if exists "Public can read chapters" on public.chapters;
create policy "Public can read chapters" on public.chapters
  for select to anon, authenticated using (true);

drop policy if exists "Public can read chapter pages" on public.chapter_pages;
create policy "Public can read chapter pages" on public.chapter_pages
  for select to anon, authenticated using (true);

-- Writes should be performed by a trusted local importer using a secret key,
-- never by the browser/client application.
